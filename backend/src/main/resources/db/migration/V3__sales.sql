-- Sales: customers, quotes, orders and invoices.
-- Lines keep the inventory item id without a foreign key: modules do not reach into each other's tables.

CREATE TABLE customers (
    id         BIGINT       NOT NULL AUTO_INCREMENT,
    tenant_id  BIGINT       NOT NULL,
    code       VARCHAR(30)  NOT NULL,
    name       VARCHAR(255) NOT NULL,
    email      VARCHAR(150) NULL,
    phone      VARCHAR(50)  NULL,
    address    VARCHAR(500) NULL,
    created_at DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NULL,
    updated_at DATETIME(6)  NULL,
    updated_by VARCHAR(100) NULL,
    version    BIGINT       NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_customers_tenant_code (tenant_id, code),
    KEY idx_customers_tenant_name (tenant_id, name),
    CONSTRAINT fk_customers_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id)
);

CREATE TABLE quotes (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    tenant_id   BIGINT        NOT NULL,
    number      VARCHAR(30)   NOT NULL,
    customer_id BIGINT        NOT NULL,
    quote_date  DATE          NOT NULL,
    valid_until DATE          NULL,
    status      VARCHAR(20)   NOT NULL,
    order_id    BIGINT        NULL,
    notes       VARCHAR(1000) NULL,
    subtotal    DECIMAL(15,2) NOT NULL DEFAULT 0,
    tax_total   DECIMAL(15,2) NOT NULL DEFAULT 0,
    total       DECIMAL(15,2) NOT NULL DEFAULT 0,
    created_at  DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by  VARCHAR(100)  NULL,
    updated_at  DATETIME(6)   NULL,
    updated_by  VARCHAR(100)  NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_quotes_tenant_number (tenant_id, number),
    KEY idx_quotes_tenant_status (tenant_id, status),
    CONSTRAINT fk_quotes_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_quotes_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE TABLE quote_lines (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    tenant_id   BIGINT        NOT NULL,
    quote_id    BIGINT        NOT NULL,
    line_no     INT           NOT NULL,
    item_id     BIGINT        NOT NULL,
    description VARCHAR(255)  NOT NULL,
    quantity    DECIMAL(15,3) NOT NULL,
    unit_price  DECIMAL(15,2) NOT NULL,
    tax_rate    DECIMAL(5,2)  NOT NULL DEFAULT 0,
    created_at  DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by  VARCHAR(100)  NULL,
    updated_at  DATETIME(6)   NULL,
    updated_by  VARCHAR(100)  NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_quote_lines_tenant_quote (tenant_id, quote_id),
    CONSTRAINT fk_quote_lines_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_quote_lines_quote FOREIGN KEY (quote_id) REFERENCES quotes (id) ON DELETE CASCADE
);

CREATE TABLE sales_orders (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    tenant_id   BIGINT        NOT NULL,
    number      VARCHAR(30)   NOT NULL,
    customer_id BIGINT        NOT NULL,
    order_date  DATE          NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    quote_id    BIGINT        NULL,
    invoice_id  BIGINT        NULL,
    notes       VARCHAR(1000) NULL,
    subtotal    DECIMAL(15,2) NOT NULL DEFAULT 0,
    tax_total   DECIMAL(15,2) NOT NULL DEFAULT 0,
    total       DECIMAL(15,2) NOT NULL DEFAULT 0,
    created_at  DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by  VARCHAR(100)  NULL,
    updated_at  DATETIME(6)   NULL,
    updated_by  VARCHAR(100)  NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_sales_orders_tenant_number (tenant_id, number),
    KEY idx_sales_orders_tenant_status (tenant_id, status),
    CONSTRAINT fk_sales_orders_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_sales_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE TABLE sales_order_lines (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    tenant_id   BIGINT        NOT NULL,
    order_id    BIGINT        NOT NULL,
    line_no     INT           NOT NULL,
    item_id     BIGINT        NOT NULL,
    description VARCHAR(255)  NOT NULL,
    quantity    DECIMAL(15,3) NOT NULL,
    unit_price  DECIMAL(15,2) NOT NULL,
    tax_rate    DECIMAL(5,2)  NOT NULL DEFAULT 0,
    created_at  DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by  VARCHAR(100)  NULL,
    updated_at  DATETIME(6)   NULL,
    updated_by  VARCHAR(100)  NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_sales_order_lines_tenant_order (tenant_id, order_id),
    CONSTRAINT fk_sales_order_lines_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_sales_order_lines_order FOREIGN KEY (order_id) REFERENCES sales_orders (id) ON DELETE CASCADE
);

CREATE TABLE invoices (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    tenant_id   BIGINT        NOT NULL,
    number      VARCHAR(30)   NOT NULL,
    customer_id BIGINT        NOT NULL,
    issue_date  DATE          NOT NULL,
    due_date    DATE          NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    order_id    BIGINT        NULL,
    notes       VARCHAR(1000) NULL,
    subtotal    DECIMAL(15,2) NOT NULL DEFAULT 0,
    tax_total   DECIMAL(15,2) NOT NULL DEFAULT 0,
    total       DECIMAL(15,2) NOT NULL DEFAULT 0,
    created_at  DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by  VARCHAR(100)  NULL,
    updated_at  DATETIME(6)   NULL,
    updated_by  VARCHAR(100)  NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_invoices_tenant_number (tenant_id, number),
    KEY idx_invoices_tenant_status (tenant_id, status),
    CONSTRAINT fk_invoices_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_invoices_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE TABLE invoice_lines (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    tenant_id   BIGINT        NOT NULL,
    invoice_id  BIGINT        NOT NULL,
    line_no     INT           NOT NULL,
    item_id     BIGINT        NOT NULL,
    description VARCHAR(255)  NOT NULL,
    quantity    DECIMAL(15,3) NOT NULL,
    unit_price  DECIMAL(15,2) NOT NULL,
    tax_rate    DECIMAL(5,2)  NOT NULL DEFAULT 0,
    created_at  DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by  VARCHAR(100)  NULL,
    updated_at  DATETIME(6)   NULL,
    updated_by  VARCHAR(100)  NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_invoice_lines_tenant_invoice (tenant_id, invoice_id),
    CONSTRAINT fk_invoice_lines_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_invoice_lines_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);
